DEFAULT_SQL = "SELECT * FROM students ORDER BY student_id;"


def _placeholder_values(count):
    return ["%s"] * count if connection.vendor == "postgresql" else ["?"] * count


def ensure_school_database():
    """Create the School Database tables and sample records."""
    with connection.cursor() as cursor:
        if connection.vendor == "postgresql":
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS students (
                    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    first_name VARCHAR(100) NOT NULL,
                    last_name VARCHAR(100) NOT NULL,
                    email VARCHAR(255) NOT NULL,
                    enrollment_year INTEGER NOT NULL
                );
                """
            )
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS courses (
                    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    course_name VARCHAR(200) NOT NULL,
                    credits INTEGER NOT NULL
                );
                """
            )
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS enrollments (
                    enrollment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    student_id INTEGER NOT NULL,
                    course_id INTEGER NOT NULL,
                    grade VARCHAR(10) NOT NULL
                );
                """
            )
        else:
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS students (
                    student_id INTEGER PRIMARY KEY,
                    first_name TEXT NOT NULL,
                    last_name TEXT NOT NULL,
                    email TEXT NOT NULL,
                    enrollment_year INTEGER NOT NULL
                );
                """
            )
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS courses (
                    course_id INTEGER PRIMARY KEY,
                    course_name TEXT NOT NULL,
                    credits INTEGER NOT NULL
                );
                """
            )
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS enrollments (
                    enrollment_id INTEGER PRIMARY KEY,
                    student_id INTEGER NOT NULL,
                    course_id INTEGER NOT NULL,
                    grade TEXT NOT NULL
                );
                """
            )

        cursor.execute("SELECT COUNT(*) FROM students")
        if cursor.fetchone()[0] == 0:
            student_sql = (
                "INSERT INTO students (first_name, last_name, email, enrollment_year) VALUES "
                + ", ".join(["(" + ", ".join(_placeholder_values(4)) + ")"] * 4)
            )
            cursor.execute(
                student_sql,
                [
                    "Alice", "Smith", "alice@example.com", 2024,
                    "Bob", "Jones", "bob@example.com", 2023,
                    "Charlie", "Brown", "charlie@example.com", 2024,
                    "Diana", "Miller", "diana@example.com", 2022,
                ],
            )

            course_sql = (
                "INSERT INTO courses (course_name, credits) VALUES "
                + ", ".join(["(" + ", ".join(_placeholder_values(2)) + ")"] * 3)
            )
            cursor.execute(
                course_sql,
                [
                    "Database Fundamentals", 3,
                    "Web Development", 3,
                    "Statistics", 2,
                ],
            )

            enrollment_sql = (
                "INSERT INTO enrollments (student_id, course_id, grade) VALUES "
                + ", ".join(["(" + ", ".join(_placeholder_values(3)) + ")"] * 5)
            )
            cursor.execute(
                enrollment_sql,
                [
                    1, 1, "A",
                    1, 2, "B",
                    2, 1, "A",
                    2, 3, "B",
                    3, 2, "A",
                ],
            )


def get_school_database_schema():
    ensure_school_database()
    tables = []
    for table_name in ["students", "courses", "enrollments"]:
        with connection.cursor() as cursor:
            if connection.vendor == "postgresql":
                cursor.execute(
                    """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = 'public' AND table_name = %s
                    ORDER BY ordinal_position
                    """,
                    [table_name],
                )
                columns = [row[0] for row in cursor.fetchall()]
            else:
                cursor.execute(f'PRAGMA table_info("{table_name}")')
                columns = [row[1] for row in cursor.fetchall()]

            cursor.execute(f'SELECT * FROM "{table_name}" ORDER BY 1 LIMIT 5')
            rows = [list(row) for row in cursor.fetchall()]
        tables.append({"name": table_name, "columns": columns, "rows": rows})
    return tables


def run_select_query(sql):
    text = (sql or "").strip()
    if not text:
        raise ValueError("Please enter a SQL statement.")
    if not text.lower().startswith("select"):
        raise ValueError("Only SELECT queries are allowed in the SQL playground.")

    statements = [part.strip() for part in text.split(";") if part.strip()]
    if len(statements) != 1:
        raise ValueError("Only one SELECT statement is allowed at a time.")

    with connection.cursor() as cursor:
        cursor.execute(text)
        columns = [field[0] for field in cursor.description] if cursor.description else []
        rows = [list(row) for row in cursor.fetchall()]
    return columns, rows


@login_required
def dashboard_redirect(request):
    """Send each user to the dashboard that belongs to their role."""
    if request.user.is_administrator:
        return redirect("administrator_dashboard")
    return redirect("learner_dashboard")


@role_required(CustomUser.Role.LEARNER)
def learner_dashboard(request):
    ensure_school_database()
    saved_query_count = request.user.saved_queries.count()
    query_history_count = request.user.query_history.count()
    progress = min(100, int((saved_query_count / 5) * 100)) if saved_query_count else 0
    context = {
        "saved_query_count": saved_query_count,
        "query_history_count": query_history_count,
        "practice_exercise_count": 3,
        "sample_database_count": 1,
        "progress_percent": progress,
    }
    return render(request, "dashboard/learner_dashboard.html", context)


@role_required(CustomUser.Role.LEARNER)
def learning_page(request):
    ensure_school_database()
    default_sql = request.GET.get("sql") or request.session.get("editor_sql") or DEFAULT_SQL
    last_result = request.session.get(
        "last_result",
        {"success": False, "columns": [], "rows": [], "row_count": 0, "error": ""},
    )
    context = {
        "database_schema": get_school_database_schema(),
        "query_history": request.user.query_history.all()[:10],
        "saved_queries": request.user.saved_queries.all()[:10],
        "default_sql": default_sql,
        "last_result": last_result,
    }
    return render(request, "dashboard/learning.html", context)


@role_required(CustomUser.Role.LEARNER)
def execute_sql(request):
    if request.method != "POST":
        return redirect("learning")

    sql = (request.POST.get("sql") or "").strip()
    request.session["editor_sql"] = sql

    try:
        columns, rows = run_select_query(sql)
    except Exception as exc:  # noqa: BLE001
        QueryHistory.objects.create(
            user=request.user,
            sql=sql,
            status="error",
            error_message=str(exc),
        )
        messages.error(request, str(exc))
        request.session["last_result"] = {
            "success": False,
            "columns": [],
            "rows": [],
            "row_count": 0,
            "error": str(exc),
        }
        return redirect("learning")

    request.session["last_result"] = {
        "success": True,
        "columns": columns,
        "rows": rows,
        "row_count": len(rows),
        "error": "",
    }
    QueryHistory.objects.create(
        user=request.user,
        sql=sql,
        status="success",
        row_count=len(rows),
    )
    messages.success(request, f"Query executed successfully. Rows returned: {len(rows)}.")
    return redirect("learning")


